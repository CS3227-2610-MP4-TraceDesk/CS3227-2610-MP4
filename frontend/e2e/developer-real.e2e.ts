import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import {
  captureDeveloperEvidence,
  ReportRealBackend,
  type ReporterFixtureMetadata,
} from './helpers/reportRealBackend'

const fixture = new ReportRealBackend()
let accounts: ReporterFixtureMetadata

test.beforeAll(async () => {
  test.setTimeout(120_000)
  accounts = await fixture.start()
})

test.afterAll(async () => {
  await fixture.stop()
})

test('real Developer workspace enforces assignment, versions, sessions and responsive access', async ({ page, browser }) => {
  test.setTimeout(90_000)
  const assignedTitle = 'Assigned browser report <img src=x onerror=window.__developerInjected=true>'
  const unassignedTitle = 'Unassigned browser report'

  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(accounts.developerLogin)
  await page.getByLabel('Password', { exact: true }).fill(fixture.credentials.password)
  await page.getByLabel('Password', { exact: true }).press('Enter')
  await expect(page.getByRole('heading', { name: 'Choose a project' })).toBeVisible()
  await page.getByRole('button', { name: 'Synthetic Reporter Project' }).click()
  await expect(page.getByRole('heading', { name: 'My work' })).toBeVisible()
  await page.getByRole('button', { name: 'Settings' }).click()
  await page.getByRole('button', { name: 'Light theme' }).click()
  await expect.poll(() => page.evaluate(() => document.documentElement.dataset.theme)).toBe('light')
  await page.getByRole('button', { name: 'My work' }).click()
  await expect(page.getByRole('heading', { name: 'My work' })).toBeVisible()
  await expect(page.getByRole('button', { name: assignedTitle })).toBeVisible()
  await expect(page.getByText(unassignedTitle, { exact: true })).toHaveCount(0)

  await page.getByRole('button', { name: 'All bugs' }).click()
  await expect(page.getByRole('heading', { name: 'All bugs' })).toBeVisible()
  await expect(page.getByRole('button', { name: assignedTitle })).toBeVisible()
  await expect(page.getByRole('button', { name: unassignedTitle })).toBeVisible()
  await page.getByRole('button', { name: unassignedTitle }).click()
  await expect(page.getByText(/· Unassigned$/)).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Private notes' })).toBeVisible()
  await expect(page.getByText(/only to the current assignee/i)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start investigation' })).toHaveCount(0)

  await page.getByRole('button', { name: 'Back to bugs' }).click()
  await page.getByRole('button', { name: assignedTitle }).click()
  await expect(page.getByRole('heading', { name: assignedTitle })).toBeVisible()
  await expect(page.getByText(/· Assigned to you$/)).toBeVisible()
  await expect(page.locator('.developer-detail script, .developer-detail img[onerror], .developer-detail b')).toHaveCount(0)
  expect(await page.evaluate(() => (window as Window & { __developerInjected?: boolean }).__developerInjected)).toBeUndefined()

  const lightAxe = await new AxeBuilder({ page }).analyze()
  expect(lightAxe.violations.map(({ id, impact }) => `${id}:${impact}`)).toEqual([])
  const desktop = await captureDeveloperEvidence(page, browser.version(), 'developer-detail-desktop-light')
  expect(desktop.horizontalOverflow).toBe(false)
  expect(desktop.shellHeader?.height).toBe(52)
  expect(desktop.sidebar?.width).toBe(275)

  await fixture.advanceDeveloperReportVersion()
  await page.getByRole('button', { name: 'Start investigation' }).click()
  await expect(page.getByRole('status').filter({ hasText: /refresh this report/i })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start investigation' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to bugs' }).click()
  await page.getByRole('button', { name: assignedTitle }).click()
  await expect(page.getByText('Version 2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Start investigation' }).click()
  await expect(page.getByText(/server confirmed the change/i)).toBeVisible()
  await expect(page.getByText('In progress', { exact: true })).toBeVisible()

  const noteText = 'Real backend private note <script>window.__noteInjected=true</script>'
  await page.getByLabel('Add a private note').fill(noteText)
  await page.getByRole('button', { name: 'Save note' }).click()
  await expect(page.getByText(noteText, { exact: true })).toBeVisible()
  await expect(page.locator('.developer-note script')).toHaveCount(0)
  expect(await page.evaluate(() => (window as Window & { __noteInjected?: boolean }).__noteInjected)).toBeUndefined()

  const rootCause = 'Real backend root cause <script>window.__resolutionInjected=true</script>'
  await page.getByLabel('Root cause').fill(rootCause)
  await page.getByLabel('Change summary').fill('Bounded synthetic change summary')
  await page.getByLabel('Verification steps').fill('1. Replay the synthetic steps')
  await page.getByLabel('Fix reference (optional)').fill('synthetic-branch')
  await fixture.advanceDeveloperReportVersion()
  await page.getByRole('button', { name: 'Send to QA' }).click()
  await expect(page.getByRole('status').filter({ hasText: /not confirmed/i })).toBeVisible()
  await expect(page.getByLabel('Root cause')).toHaveValue(rootCause)
  await page.getByRole('button', { name: 'Refresh bug' }).click()
  await expect(page.getByLabel('Root cause')).toHaveValue(rootCause)
  await page.getByRole('button', { name: 'Send to QA' }).click()
  await expect(page.getByText(/sent to QA after server confirmation/i)).toBeVisible()
  await expect(page.locator('.developer-detail-top').getByText('Ready for QA', { exact: true })).toBeVisible()
  await expect(page.getByText(rootCause, { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Send to QA' })).toHaveCount(0)
  expect(await page.evaluate(() => (window as Window & { __resolutionInjected?: boolean }).__resolutionInjected)).toBeUndefined()

  const sendBackReason = 'Please verify <b>two distinct refunds</b> after refreshing.'
  const qaContext = await browser.newContext({ ignoreHTTPSErrors: true })
  try {
    const qa = await qaContext.newPage()
    const baseUrl = new URL(page.url()).origin
    await qa.goto(`${baseUrl}/`)
    await qa.getByLabel('Email', { exact: true }).fill(accounts.qaLogin)
    await qa.getByLabel('Password', { exact: true }).fill(fixture.credentials.password)
    await qa.getByLabel('Password', { exact: true }).press('Enter')
    await qa.getByRole('button', { name: 'Synthetic Reporter Project' }).click()
    const queue = qa.getByRole('region', { name: 'Verification', exact: true })
    await expect(queue.getByRole('button', { name: new RegExp(assignedTitle.split(' <')[0]) })).toBeVisible()
    await expect(queue.getByText(unassignedTitle, { exact: true })).toHaveCount(0)
    await queue.getByText(assignedTitle, { exact: true }).click()
    const summary = qa.getByRole('article', { name: 'Bug review summary' })
    await summary.getByText('Proposed fix · Revision 1').click()
    await expect(summary.getByText(rootCause, { exact: true })).toBeVisible()
    await expect(summary.getByText('synthetic-branch', { exact: true })).toBeVisible()
    await expect(summary.getByText(noteText, { exact: true })).toHaveCount(0)
    expect(await qa.evaluate(() => (window as Window & { __resolutionInjected?: boolean }).__resolutionInjected)).toBeUndefined()

    const overview = qa.getByRole('button', { name: 'Bug overview', exact: true })
    await overview.focus()
    await qa.keyboard.press('Enter')
    const reviewItems = qa.getByRole('region', { name: 'Review items' })
    await reviewItems.getByRole('button', { name: 'Original report' }).focus()
    await qa.keyboard.press('Enter')
    await expect(summary.locator('#qa-review-report > summary')).toBeFocused()
    await expect(summary.locator('#qa-review-report')).toHaveAttribute('open', '')

    const qaReviewRoute = `${baseUrl}/api/projects/${accounts.projectId}/reports/${accounts.assignedReportId}/qa-suggestions`
    const missingCsrf = await qa.request.post(qaReviewRoute, { data: { expectedVersion: 1 } })
    expect(missingCsrf.status()).toBe(403)
    expect(await missingCsrf.json()).toMatchObject({ error: { code: 'CSRF_INVALID' } })

    await qa.getByRole('button', { name: 'Review with AI' }).click()
    const panel = qa.getByRole('region', { name: 'Review with AI' })
    await panel.getByRole('button', { name: 'Generate review' }).click()
    await expect(panel.getByText('Replay the synthetic steps and compare the result.')).toBeVisible()
    await expect(panel.getByText('Record the build used for verification.')).toBeVisible()
    const addPlanChecks = panel.getByRole('button', { name: 'Add selected to Verification' })
    await expect(addPlanChecks).toBeDisabled()
    await panel.getByRole('checkbox', { name: 'Replay the synthetic steps and compare the result.' }).click()
    await addPlanChecks.click()
    await expect(panel.getByRole('status')).toContainText('Added 1 pending check to the draft.')
    await panel.getByLabel('Ask a follow-up').fill('What should I compare after refresh?')
    await panel.getByRole('button', { name: 'Send question' }).click()
    const followUp = panel.getByRole('article', { name: 'Follow-up 1' })
    await expect(followUp.getByText('Compare the totals before and after refreshing twice.')).toBeVisible()
    await followUp.getByRole('checkbox', { name: 'Refresh a payment with two distinct refunds.' }).click()
    await followUp.getByRole('button', { name: 'Add selected to Verification' }).click()
    await expect(summary.getByRole('heading', { name: assignedTitle })).toBeVisible()
    for (const width of [390, 320]) {
      await qa.setViewportSize({ width, height: 844 })
      expect(await qa.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
      await expect(summary.getByText('synthetic-branch', { exact: true })).toBeVisible()
    }
    const qaAxe = await new AxeBuilder({ page: qa }).analyze()
    expect(qaAxe.violations.map(({ id, impact }) => `${id}:${impact}`)).toEqual([])

    await panel.getByRole('button', { name: 'Close AI review' }).click()
    await expect(qa.getByRole('button', { name: 'Review with AI' })).toBeFocused()
    const verificationRoute = `${baseUrl}/api/projects/${accounts.projectId}/reports/${accounts.assignedReportId}/qa-verification`
    const verificationWithoutCsrf = await qa.request.post(verificationRoute, { data: {} })
    expect(verificationWithoutCsrf.status()).toBe(403)
    expect(await verificationWithoutCsrf.json()).toMatchObject({ error: { code: 'CSRF_INVALID' } })
    expect((await page.request.get(verificationRoute)).status()).toBe(403)

    await overview.focus()
    await qa.keyboard.press('Enter')
    await reviewItems.getByRole('button', { name: 'Verification' }).focus()
    await qa.keyboard.press('Enter')
    await expect(qa.getByRole('region', { name: 'Verification checklist' })).toBeFocused()
    await expect(qa.getByRole('button', { name: /Replay the synthetic steps/ })).toBeVisible()
    await expect(qa.getByRole('button', { name: /Refresh a payment with two distinct refunds/ })).toBeVisible()
    await qa.getByRole('textbox', { name: 'New check' }).fill('Confirm only one refund row')
    await qa.getByRole('button', { name: 'Add check' }).click()
    await qa.getByLabel('Verification notes').fill('Verified on synthetic staging')
    await qa.setViewportSize({ width: 1440, height: 900 })
    await qa.getByRole('button', { name: 'Back to verification queue' }).click()
    const allBugs = qa.getByRole('button', { name: 'All bugs', exact: true })
    if (!(await allBugs.isVisible())) await qa.getByRole('button', { name: 'Toggle sidebar' }).click()
    await allBugs.click()
    const allQueue = qa.getByRole('region', { name: 'All bugs', exact: true })
    await allQueue.getByText(unassignedTitle, { exact: true }).click()
    await expect(summary.getByRole('heading', { name: unassignedTitle })).toBeVisible()
    await expect(qa.getByRole('region', { name: 'Verification checklist' })).toHaveCount(0)
    await qa.getByRole('button', { name: 'Back to all bugs' }).click()
    await allQueue.getByText(assignedTitle, { exact: true }).click()
    await expect(qa.getByRole('group', { name: 'Bug review sections' })
      .getByRole('button', { name: 'Verification' })).toHaveAttribute('aria-pressed', 'true')
    await expect(qa.getByLabel('Verification notes')).toHaveValue('Verified on synthetic staging')
    await qa.getByRole('button', { name: 'Save verification' }).click()
    await expect(qa.getByText('Verification saved.')).toBeVisible()
    const reloadVerification = qa.waitForResponse(response =>
      response.url().endsWith('/qa-verification') && response.request().method() === 'GET' && response.ok())
    await qa.getByRole('button', { name: 'Reload verification' }).click()
    await reloadVerification
    await expect(qa.getByLabel('Verification notes')).toHaveValue('Verified on synthetic staging')
    await expect(qa.getByRole('button', { name: /Refresh a payment with two distinct refunds/ })).toBeVisible()
    await expect(qa.getByRole('button', { name: /Confirm only one refund row/ })).toBeVisible()
    await expect(qa.getByRole('button', { name: 'Verify and close' })).toBeDisabled()
    const foreign = await qa.request.get(`${baseUrl}/api/projects/${accounts.deniedProjectId}/reports/${accounts.assignedReportId}/resolutions`)
    expect(foreign.status()).toBe(404)
    await qa.getByLabel('Reason for sending back').fill(sendBackReason)
    await qa.getByRole('button', { name: 'Send back to Developer' }).click()
    await expect(qa.getByText('Bug sent back to the Developer.', { exact: true })).toBeVisible()
    await qa.getByRole('button', { name: 'Settings' }).click()
    await qa.getByRole('button', { name: 'Choose another project' }).click()
    await expect(qa.getByRole('heading', { name: 'Choose a project' })).toBeVisible()
    await expect(summary).toHaveCount(0)
  } finally {
    await qaContext.close()
  }

  await page.getByRole('button', { name: 'Back to bugs' }).click()
  await page.getByRole('button', { name: assignedTitle }).click()
  const resolutionPanel = page.getByRole('region', { name: 'Proposed resolution' })
  await expect(resolutionPanel.getByText('QA send-back reason', { exact: true })).toBeVisible()
  await expect(resolutionPanel.getByText(sendBackReason, { exact: true })).toBeVisible()
  await expect(resolutionPanel.locator('dd b')).toHaveCount(0)
  await page.getByLabel('Root cause').fill('Revised refund investigation')
  await page.getByLabel('Change summary').fill('Preserve distinct refunds')
  await page.getByLabel('Verification steps').fill('Refresh with two distinct refunds')
  await page.getByRole('button', { name: 'Send to QA' }).click()
  await expect(resolutionPanel.getByText(/Revision 2 ·/)).toBeVisible()
  await expect(resolutionPanel.getByText(sendBackReason, { exact: true })).not.toBeVisible()
  await resolutionPanel.getByText('Earlier revisions (1)', { exact: true }).click()
  await expect(resolutionPanel.getByRole('listitem').filter({ hasText: /Revision 1 ·/ })
    .getByText(sendBackReason, { exact: true })).toBeVisible()

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  const mobile390 = await captureDeveloperEvidence(page, browser.version(), 'developer-detail-390-reduced-motion')
  expect(mobile390.horizontalOverflow).toBe(false)
  expect(mobile390.reducedMotion).toBe(true)
  expect(mobile390.shellTransition).toBe('none')
  const sidebarToggle = page.getByRole('button', { name: 'Toggle sidebar' })
  await sidebarToggle.click()
  await expect(page.getByRole('button', { name: 'Close navigation' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(sidebarToggle).toBeFocused()
  await page.setViewportSize({ width: 320, height: 844 })
  const mobile320 = await captureDeveloperEvidence(page, browser.version(), 'developer-detail-320-reduced-motion')
  expect(mobile320.horizontalOverflow).toBe(false)
  expect(mobile320.rail?.width).toBe(40)

  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('button', { name: 'Settings' }).click()
  await page.getByRole('button', { name: 'Dark theme' }).click()
  await expect.poll(() => page.evaluate(() => document.documentElement.dataset.theme)).toBe('dark')
  await page.evaluate(async () => {
    const animations = document.querySelector('.developer-settings')?.getAnimations({ subtree: true }) ?? []
    await Promise.all(animations.map(animation => animation.finished.catch(() => undefined)))
  })
  const darkAxe = await new AxeBuilder({ page }).analyze()
  expect(darkAxe.violations.map(({ id, impact, nodes }) => ({
    id,
    impact,
    nodes: nodes.map(node => ({ target: node.target, html: node.html, failureSummary: node.failureSummary })),
  }))).toEqual([])
  await page.getByRole('button', { name: 'My work' }).click()
  await page.getByRole('button', { name: assignedTitle }).click()
  await expect(page.getByRole('heading', { name: assignedTitle })).toBeVisible()

  await page.getByRole('button', { name: 'Edit' }).click()
  const edit = page.getByLabel('Edit private note')
  await edit.fill('Unsaved edit retained only until assignment denial is confirmed')
  await fixture.reassignDeveloperReport()
  await page.getByRole('listitem').filter({ has: edit }).getByRole('button', { name: 'Save note' }).click()
  await expect(page.getByRole('heading', { name: 'Private notes' })).toBeVisible()
  await expect(page.getByText(/only to the current assignee/i)).toBeVisible()
  await expect(page.getByText(/assignment changed/i).first()).toBeVisible()
  await expect(page.getByLabel('Add a private note')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit' })).toHaveCount(0)
  await expect(page.getByText(noteText, { exact: true })).toHaveCount(0)
  await expect(page.getByText('Unsaved edit retained only until assignment denial is confirmed', { exact: true })).toHaveCount(0)

  await fixture.invalidateDeveloperSessions()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  await expect(page.getByText(noteText, { exact: true })).toHaveCount(0)
})
